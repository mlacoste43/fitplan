export const ACTIVITY_COEFFICIENTS = {
  sedentary:   1.2,
  light:       1.375,
  moderate:    1.55,
  active:      1.725,
  very_active: 1.9,
};

export const ACTIVITY_LABELS = {
  sedentary:   "🪑 Сидячий — без тренировок",
  light:       "🚶 Лёгкий — 1-3 раза в неделю",
  moderate:    "🏃 Умеренный — 3-5 раз в неделю",
  active:      "💪 Активный — 6-7 раз в неделю",
  very_active: "🔥 Очень активный — физический труд",
};

export function calculateCalories({ gender, age, weight, height, goal, activity = "moderate" }) {
  const bmr =
    gender === "male"
      ? 10 * weight + 6.25 * height - 5 * age + 5
      : 10 * weight + 6.25 * height - 5 * age - 161;

  const pal  = ACTIVITY_COEFFICIENTS[activity] ?? 1.55;
  const tdee = bmr * pal;

  const calorieAdj = { lose: -400, gain: 300, relief: -200, maintain: 0 };
  const proteinK   = { lose: 2.0,  gain: 2.2, relief: 2.5,  maintain: 1.8 };
  const fatK       = { lose: 0.8,  gain: 1.0, relief: 0.7,  maintain: 0.9 };

  const calories = tdee + calorieAdj[goal];
  const protein  = weight * proteinK[goal];
  const fat      = weight * fatK[goal];
  const carbs    = Math.max((calories - protein * 4 - fat * 9) / 4, 0);

  return {
    calories: Math.round(calories),
    protein:  Math.round(protein),
    fat:      Math.round(fat),
    carbs:    Math.round(carbs),
  };
}

