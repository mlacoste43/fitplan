// Форматирование плана питания с КБЖУ по каждому приёму
export function formatNutritionPlan(plan) {
  if (!Array.isArray(plan)) return String(plan);

  let text = "";
  let totalKcal = 0, totalP = 0, totalF = 0, totalC = 0;

  for (const block of plan) {
    const bKcal = block.items.reduce((s, i) => s + i.kcal, 0);
    const bP    = block.items.reduce((s, i) => s + i.p,    0);
    const bF    = block.items.reduce((s, i) => s + i.f,    0);
    const bC    = block.items.reduce((s, i) => s + i.c,    0);

    text += `${block.meal} — ${bKcal} ккал | Б:${bP} Ж:${bF} У:${bC}\n`;
    for (const item of block.items) {
      text += `  • ${item.name} (${item.amount})\n`;
      text += `    ${item.kcal} ккал  Б:${item.p}  Ж:${item.f}  У:${item.c}\n`;
    }
    text += "\n";

    totalKcal += bKcal;
    totalP    += bP;
    totalF    += bF;
    totalC    += bC;
  }

  text += `─────────────────\n`;
  text += `Итого за день:\n`;
  text += `🔥 ${totalKcal} ккал\n`;
  text += `Б: ${totalP}г  |  Ж: ${totalF}г  |  У: ${totalC}г`;

  return text;
}

