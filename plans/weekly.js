export function getCurrentWeekNumber() {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 1);
  return Math.ceil(((now - start) / 86400000 + start.getDay() + 1) / 7);
}

export function getWeekNumber() {
  return (getCurrentWeekNumber() % 4) + 1;
}

